#!/usr/bin/env python3
"""Install and verify the pinned compiled eSpeak data in an Apple app bundle.

The retained data was generated by scripts/build-android-speech-data.py from the
same eSpeak revision used by the Apple Swift package. No network is used.
"""
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import sys

REVISION = "699e79690f23e2558d990a3a78b0050745b96932"
MANIFEST_SHA256 = "4263b09040184a4e5323f64d9d7cb6ad2f05502fa287471a6e2ca9c4463ede29"
RESOURCE = "vipi-speech-699e7969"
REQUIRED = {"sw_dict", "phondata", "phonindex", "phontab", "intonations", "lang/bnt/sw"}


def digest(path):
    with path.open("rb") as stream:
        value = hashlib.sha256()
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(chunk)
        return value.hexdigest()


def verify(root, rows):
    actual = set()
    data = root / "espeak-ng-data"
    if not data.is_dir() or data.is_symlink():
        raise ValueError("Missing speech data directory")
    for path in data.rglob("*"):
        if path.is_symlink():
            raise ValueError("Speech data must not contain symlinks: " + str(path))
        if path.is_file():
            actual.add(path.relative_to(root).as_posix())
    expected = set()
    for row in rows:
        name = row["path"]
        parts = PurePosixPath(name).parts
        if not parts or parts[0] != "espeak-ng-data" or any(p in ("", ".", "..") for p in name.split("/")) or "\\" in name:
            raise ValueError("Unsafe speech data path: " + name)
        if name in expected:
            raise ValueError("Duplicate speech data path: " + name)
        expected.add(name)
        path = root / name
        if not path.is_file() or path.stat().st_size != row["bytes"] or digest(path) != row["sha256"]:
            raise ValueError("Speech data differs: " + name)
    if actual != expected:
        raise ValueError("Speech data file set differs from manifest")
    if not {"espeak-ng-data/" + name for name in REQUIRED} <= expected:
        raise ValueError("Required Swahili speech data absent")


def main():
    source = Path(__file__).resolve().parent.parent / "android/app/src/main/assets/speech/espeak-ng-699e7969"
    manifest_path = source / "manifest.json"
    if digest(manifest_path) != MANIFEST_SHA256:
        raise ValueError("Speech manifest differs from the pinned reviewed manifest")
    manifest = json.loads(manifest_path.read_text())
    if manifest.get("schema") != "vipi-native-speech-data-1" or manifest.get("espeak_revision") != REVISION or "sw" not in manifest.get("dictionary_languages", []):
        raise ValueError("Unexpected speech data provenance")
    rows = manifest["files"]
    verify(source, rows)
    app = Path(os.environ["TARGET_BUILD_DIR"]) / os.environ["UNLOCALIZED_RESOURCES_FOLDER_PATH"]
    if not app.is_dir():
        raise ValueError("Built app resource directory is absent: " + str(app))
    destination = app / RESOURCE
    if destination.is_symlink():
        raise ValueError("Speech destination is a symlink")
    # Xcode owns this build output. Remove only this generated resource, ensuring
    # stale files from a previous build cannot survive a changed manifest.
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source / "espeak-ng-data", destination / "espeak-ng-data", symlinks=False)
    shutil.copyfile(manifest_path, destination / "manifest.json")
    verify(destination, rows)
    if digest(destination / "manifest.json") != MANIFEST_SHA256:
        raise ValueError("Packaged speech manifest digest differs")
    print(f"Verified {len(rows)} compiled speech files in {destination}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print("error: Speech resource verification failed: " + str(exc), file=sys.stderr)
        sys.exit(1)
