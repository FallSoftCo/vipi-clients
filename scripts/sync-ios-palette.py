#!/usr/bin/env python3
"""Generate native adaptive roles from the reviewed design matrix, no runtime IO."""

from pathlib import Path
import json, re

root = Path(__file__).resolve().parents[1]
v = json.loads((root / "design/palette.json").read_text())
keys = list(v["light"])
variants = ["light", "dark", "increased_contrast_light", "increased_contrast_dark"]
assert all(set(v[x]) == set(keys) for x in variants)


def color(value):
    assert re.fullmatch(r"#[0-9A-Fa-f]{6}", value)
    return "0x" + value[1:].upper()


names = {
    k: k.split("_")[0] + "".join(w.title() for w in k.split("_")[1:]) for k in keys
}
s = "import SwiftUI\n\n// Generated by scripts/sync-ios-palette.py from design/palette.json.\nenum VipiColorRole:String,CaseIterable {\n"
for k, n in names.items():
    s += "    case " + n + (' = "' + k + '"' if n != k else "") + "\n"
s += "}\n\n/// Opaque sRGB roles; native traits choose appearance and increased contrast.\nenum VipiPalette {\n    private static let roles:[VipiColorRole:[UInt32]] = [\n"
for k, n in names.items():
    s += "        ." + n + ":[" + ",".join(color(v[t][k]) for t in variants) + "],\n"
s += """    ]
    static func uiColor(_ role:VipiColorRole) -> UIColor {
        let values = roles[role]!
        return UIColor { traits in
            let dark = traits.userInterfaceStyle == .dark,high = traits.accessibilityContrast == .high
            let hex = values[(high ? 2:0)+(dark ? 1:0)]
            return UIColor(red:CGFloat((hex>>16)&255)/255,green:CGFloat((hex>>8)&255)/255,blue:CGFloat(hex&255)/255,alpha:1)
        }
    }
    static func color(_ role:VipiColorRole) -> Color { Color(uiColor:uiColor(role)) }
    static func avatar(_ slot:Int) -> Color {
        precondition((0..<4).contains(slot))
"""
for name in ["light", "dark"]:
    s += (
        "        let "
        + name
        + ":[UInt32] = ["
        + ",".join(color(x) for x in v["avatar_" + name])
        + "]\n"
    )
s += """        return Color(uiColor:UIColor { traits in
            let hex = (traits.userInterfaceStyle == .dark ? dark:light)[slot]
            return UIColor(red:CGFloat((hex>>16)&255)/255,green:CGFloat((hex>>8)&255)/255,blue:CGFloat(hex&255)/255,alpha:1)
        })
    }
}

private struct OutgoingMessageKey:EnvironmentKey { static let defaultValue = false }
extension EnvironmentValues {
    var vipiOutgoingMessage:Bool {
        get { self[OutgoingMessageKey.self] }
        set { self[OutgoingMessageKey.self] = newValue }
    }
}
"""
depth = v["light_bubble_depth"]
shadow = int(depth["shadow_color"][1:], 16)
s += "\nenum VipiLightBubbleDepth {\n"
s += "    static let strokeWidth:CGFloat = " + str(depth["stroke_width"]) + "\n"
s += (
    "    static let shadowColor = Color(red:"
    + str((shadow >> 16) & 255)
    + "/255.0,green:"
    + str((shadow >> 8) & 255)
    + "/255.0,blue:"
    + str(shadow & 255)
    + "/255.0)\n"
)
for field, name in [
    ("shadow_opacity", "shadowOpacity"),
    ("shadow_radius", "shadowRadius"),
    ("shadow_y", "shadowY"),
]:
    s += (
        "    static let "
        + name
        + ":"
        + ("Double" if field == "shadow_opacity" else "CGFloat")
        + " = "
        + str(depth[field])
        + "\n"
    )
s += "}\n"
(root / "ios/Vipi/VipiPalette.swift").write_text(s)
